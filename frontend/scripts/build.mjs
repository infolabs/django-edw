#!/usr/bin/env node
/*
 * Офлайн-сборка production-бандла django-edw через предсобранное дерево
 * зависимостей (esbuild вместо webpack: в /home/agent/workspace/venvs/edw-frontend
 * webpack отсутствует, npm install запрещён).
 *
 * Сборка детерминирована: одинаковый вход даёт побайтно одинаковый выход
 * (scripts/check.sh проверяет это двойным прогоном и сравнением sha256).
 *
 * Usage: node scripts/build.mjs [outfile]
 *   по умолчанию backend/edw/static/edw/js/bundle.js
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

import {
  BUNDLE_FILE,
  NODE_MODULES,
  SRC_DIR,
  baseOptions,
  esbuild,
} from './buildlib.mjs';

const {build} = esbuild;


const BANNER = '/* EDW django-edw production bundle (React 18.3). '
  + 'Generated by frontend/scripts/build.mjs, do not edit. */';


function sha256(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}


async function main() {
  const outfile = process.argv[2] ? path.resolve(process.argv[2]) : BUNDLE_FILE;

  fs.mkdirSync(path.dirname(outfile), {recursive: true});

  const result = await build({
    ...baseOptions(),
    entryPoints: [path.join(SRC_DIR, 'index.js')],
    outfile,
    format: 'iife',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    sourcemap: false,
    legalComments: 'none',
    metafile: true,
    banner: {js: BANNER},
  });

  const bundle = fs.readFileSync(outfile);
  const modules = Object.keys(result.metafile.inputs);
  const vendorFallbacks = modules
    .filter((name) => name.startsWith('src/vendor/'))
    .map((name) => path.basename(name))
    .sort();

  console.log('BUILD OK');
  console.log(`  node_modules: ${NODE_MODULES}`);
  console.log(`  bundle: ${outfile} (${bundle.length} байт)`);
  console.log(`  sha256: ${sha256(bundle)}`);
  console.log(`  модулей в графе: ${modules.length}`);
  console.log(`  офлайн-заглушки vendor: ${vendorFallbacks.length ? vendorFallbacks.join(', ') : 'нет (все пакеты установлены)'}`);
}

main().catch((error) => {
  console.error('BUILD FAIL');
  console.error(error && error.message ? error.message : error);
  process.exit(1);
});
